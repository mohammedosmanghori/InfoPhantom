import React, { useState } from 'react';
import {
  X,
  Printer,
  FileDown,
  FileCode,
  Copy,
  Check,
  Download,
  ShieldCheck,
  AlertTriangle,
  GitCompare,
  CheckSquare,
} from 'lucide-react';
import { AnalysisResult } from '../types';

interface ExportModalProps {
  result: AnalysisResult | null;
  onClose: () => void;
}

export function ExportModal({ result, onClose }: ExportModalProps) {
  const [copied, setCopied] = useState(false);

  if (!result) return null;

  // Generate clean Markdown representation
  const generateMarkdown = () => {
    return `# InfoPhantom — RESEARCH VERIFICATION AUDIT
**Tagline:** Uncovers information hidden between scattered sources.
**Research Question:** ${result.researchQuestion}
**Generated:** ${new Date(result.analyzedAt).toLocaleString()}
**Overall Assessment:** ${result.summary.overallConfidence}

---

## 1. Executive Summary
${result.summary.keyTakeaway}

- **Sources Analyzed:** ${result.summary.totalSources}
- **Claims Extracted:** ${result.summary.claimsExtracted}
- **Information Gaps (Dark Spots):** ${result.summary.gapsDetected}
- **Potential Conflicts:** ${result.summary.conflictsFound}
- **Outdated / Archived Notices:** ${result.summary.outdatedSourcesCount}

---

## 2. Information Gaps Detected (Crucial Omissions)
${result.informationGaps
  .map(
    (gap, i) => `### Gap ${i + 1}: ${gap.title} [${gap.severity}]
- **Forensic Finding:** ${gap.explanation}
- **Why It Matters (Applicant Risk):** ${gap.whyItMatters}
- **Missing Information:** ${gap.missingInformation}
- **Sources Reviewed:** ${gap.reviewedSources.join(', ')}
- **Recommended Action:** ${gap.recommendedAction}
`
  )
  .join('\n')}

---

## 3. Potential Conflicts Across Sources
${result.conflicts
  .map(
    (c, i) => `### Conflict ${i + 1}: ${c.conflictingClaim} [Risk: ${c.riskLevel}]
- **Source A (${c.sourceAReference}):** "${c.directExcerptA}"
- **Source B (${c.sourceBReference}):** "${c.directExcerptB}"
- **Divergence Analysis:** ${c.divergenceAnalysis}
- **Reconciliation Recommendation:** ${c.reconciliationRecommendation}
`
  )
  .join('\n')}

---

## 4. Outdated / Superseded Notices Flagged
${result.outdatedInformation
  .map(
    (o, i) => `### Outdated Notice ${i + 1}: ${o.sourceTitle}
- **Detected Date:** ${o.detectedDate}
- **Applicable Cycle:** ${o.applicableCycle}
- **Reason:** ${o.reasonWhyOutdated}
- **Warning:** ${o.criticalWarning}
`
  )
  .join('\n')}

---

## 5. Prioritized Verification Checklist
${result.verificationChecklist
  .map(
    (item) => `- [${item.completed ? 'x' : ' '}] **(${item.priority})** ${item.task}
  *Category:* ${item.category} | *Source:* ${item.sourceReference}
  *Action:* ${item.verificationAction}${item.notes ? `\n  *User Note:* ${item.notes}` : ''}`
  )
  .join('\n')}

---
*Report generated by InfoPhantom | Shinchan Online Hackathon 2026*
`;
  };

  const handleDownloadMarkdown = () => {
    const md = generateMarkdown();
    const blob = new Blob([md], { type: 'text/markdown;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `infophantom-report-${Date.now()}.md`;
    link.click();
    URL.revokeObjectURL(url);
  };

  const handleDownloadJson = () => {
    const jsonStr = JSON.stringify(result, null, 2);
    const blob = new Blob([jsonStr], { type: 'application/json;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `infophantom-audit-${Date.now()}.json`;
    link.click();
    URL.revokeObjectURL(url);
  };

  const handlePrint = () => {
    window.print();
  };

  const handleCopySummary = () => {
    const summary = `InfoPhantom VERIFICATION REPORT:
Question: ${result.researchQuestion}
Assessment: ${result.summary.overallConfidence}
Key Takeaway: ${result.summary.keyTakeaway}

Gaps Detected: ${result.informationGaps.length}
Conflicts: ${result.conflicts.length}
Top Next Steps:
${result.verificationChecklist.slice(0, 3).map((c, i) => `${i + 1}. ${c.task}`).join('\n')}`;

    navigator.clipboard.writeText(summary);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-950/80 backdrop-blur-sm animate-in fade-in duration-150 no-print">
      <div className="relative w-full max-w-2xl bg-[#0c1427] border border-[#1e2f54] rounded-2xl shadow-2xl overflow-hidden flex flex-col">
        {/* Header */}
        <div className="p-5 border-b border-[#1a2744] flex items-center justify-between">
          <div className="flex items-center gap-2">
            <span className="p-1.5 rounded-lg bg-cyan-500/10 text-cyan-400 border border-cyan-500/30">
              <Download className="w-4 h-4" />
            </span>
            <h2 className="text-base font-bold text-white">
              Export Research Audit Report
            </h2>
          </div>
          <button
            onClick={onClose}
            className="p-1.5 text-slate-400 hover:text-white rounded-lg hover:bg-[#182643]"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Export Options Grid */}
        <div className="p-6 space-y-4">
          <p className="text-xs text-slate-300 leading-relaxed">
            Choose an export format for your forensic research verification packet, including evidence quotes, detected gaps, side-by-side conflict comparisons, and the prioritized checklist.
          </p>

          <div className="grid grid-cols-1 sm:grid-cols-2 gap-3 pt-2">
            {/* Option 1: Print / PDF */}
            <div
              onClick={handlePrint}
              className="p-4 rounded-xl bg-[#080d1a] border border-[#1b2844] hover:border-cyan-500/50 cursor-pointer group transition-all space-y-2"
            >
              <div className="w-8 h-8 rounded-lg bg-cyan-500/10 text-cyan-400 flex items-center justify-center group-hover:scale-105 transition-transform">
                <Printer className="w-4 h-4" />
              </div>
              <h3 className="text-sm font-bold text-white group-hover:text-cyan-300">
                Print / Save as PDF
              </h3>
              <p className="text-xs text-slate-400 leading-relaxed">
                Generates a clean, formal print layout with executive summary, tables, and full checklists.
              </p>
            </div>

            {/* Option 2: Markdown */}
            <div
              onClick={handleDownloadMarkdown}
              className="p-4 rounded-xl bg-[#080d1a] border border-[#1b2844] hover:border-cyan-500/50 cursor-pointer group transition-all space-y-2"
            >
              <div className="w-8 h-8 rounded-lg bg-blue-500/10 text-blue-400 flex items-center justify-center group-hover:scale-105 transition-transform">
                <FileDown className="w-4 h-4" />
              </div>
              <h3 className="text-sm font-bold text-white group-hover:text-blue-300">
                Download Markdown (.md)
              </h3>
              <p className="text-xs text-slate-400 leading-relaxed">
                Formatted markdown document ready to import into Notion, Obsidian, GitHub, or documentation portals.
              </p>
            </div>

            {/* Option 3: JSON Audit Package */}
            <div
              onClick={handleDownloadJson}
              className="p-4 rounded-xl bg-[#080d1a] border border-[#1b2844] hover:border-cyan-500/50 cursor-pointer group transition-all space-y-2"
            >
              <div className="w-8 h-8 rounded-lg bg-indigo-500/10 text-indigo-400 flex items-center justify-center group-hover:scale-105 transition-transform">
                <FileCode className="w-4 h-4" />
              </div>
              <h3 className="text-sm font-bold text-white group-hover:text-indigo-300">
                Download JSON Package
              </h3>
              <p className="text-xs text-slate-400 leading-relaxed">
                Machine-readable structured JSON file containing all claims, anchors, severities, and checklist states.
              </p>
            </div>

            {/* Option 4: Copy to Clipboard */}
            <div
              onClick={handleCopySummary}
              className="p-4 rounded-xl bg-[#080d1a] border border-[#1b2844] hover:border-cyan-500/50 cursor-pointer group transition-all space-y-2"
            >
              <div className="w-8 h-8 rounded-lg bg-emerald-500/10 text-emerald-400 flex items-center justify-center group-hover:scale-105 transition-transform">
                {copied ? <Check className="w-4 h-4" /> : <Copy className="w-4 h-4" />}
              </div>
              <h3 className="text-sm font-bold text-white group-hover:text-emerald-300">
                {copied ? 'Copied to Clipboard!' : 'Copy Brief Summary'}
              </h3>
              <p className="text-xs text-slate-400 leading-relaxed">
                Copies quick executive briefing text to clipboard for sharing in Slack, emails, or chat.
              </p>
            </div>
          </div>
        </div>

        {/* Footer */}
        <div className="p-4 border-t border-[#1a2744] flex items-center justify-between text-xs text-slate-400 bg-[#0a1020]">
          <span>InfoPhantom Compliance Package</span>
          <button
            onClick={onClose}
            className="px-4 py-1.5 rounded-lg bg-[#14203a] hover:bg-[#1b2b4e] text-slate-200 text-xs font-semibold"
          >
            Close
          </button>
        </div>
      </div>
    </div>
  );
}
